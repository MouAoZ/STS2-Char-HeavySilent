namespace HeavySilent.Cards.Skills;

/// <summary>HS-SKL-021：留招。</summary>
[CustomID("HEAVYSILENT_RESERVE")]
public sealed class Reserve() : HeavySilentCard(1, CardType.Skill, CardRarity.Uncommon, TargetType.Self)
{
    public override bool GainsBlock => true;
    protected override IEnumerable<DynamicVar> CanonicalVars => [new BlockVar(7, ValueProp.Move)];
    protected override IEnumerable<IHoverTip> ExtraHoverTips => [HoverTipFactory.FromKeyword(CardKeyword.Retain)];
    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay cardPlay)
    {
        await CreatureCmd.GainBlock(Owner.Creature, DynamicVars.Block, cardPlay);
        CardModel? selected = (await CardSelectCmd.FromHand(choiceContext, Owner,
            new CardSelectorPrefs(SelectionScreenPrompt, 1), c => !c.Keywords.Contains(CardKeyword.Retain), this)).FirstOrDefault();
        if (selected != null) CardCmd.ApplyKeyword(selected, CardKeyword.Retain);
    }
    protected override void OnUpgrade() => DynamicVars.Block.UpgradeValueBy(2);
}
